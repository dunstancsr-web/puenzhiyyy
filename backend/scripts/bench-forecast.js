// ─────────────────────────────────────────────────────────────────────────────
// FORECAST BENCHMARK (MVP2 Day 2)
//
// Run from backend/ (no server needed, no model call, free):
//   node scripts/bench-forecast.js                every active SKU, every model
//   node scripts/bench-forecast.js TJ-25KG         one SKU
//   node scripts/bench-forecast.js --report        also write a markdown table
//
// Calls backtest() from src/engines/forecast.js directly — the exact function
// the recompute API route calls, not a copy — so this script's numbers are
// what auto-mode actually picks, following the same rule bench-models.js's
// TASK-94 rewrite set: the score has to describe the real path.
// ─────────────────────────────────────────────────────────────────────────────

const { getDb, initDb } = require("../src/db/init");
const { backtest, MODEL_IDS, monthlySeries } = require("../src/engines/forecast");

const args = process.argv.slice(2);
const REPORT = args.includes("--report");
const ONLY_SKU = args.find((a) => !a.startsWith("--"));

function main() {
  initDb();
  const db = getDb();
  const skus = db.prepare(`SELECT sku_id, product_name FROM skus WHERE active = 1 ORDER BY sku_id`).all()
    .filter((s) => !ONLY_SKU || s.sku_id === ONLY_SKU);

  if (!skus.length) {
    console.error(ONLY_SKU ? `No active SKU '${ONLY_SKU}'` : "No active SKUs");
    process.exit(1);
  }

  const rows = [];
  for (const sku of skus) {
    const months = monthlySeries(db, sku.sku_id).length;
    const result = backtest(db, sku.sku_id, MODEL_IDS);
    rows.push({ sku_id: sku.sku_id, name: sku.product_name, months, ...result });
  }

  const pad = (s, n) => String(s).padEnd(n);
  console.log(pad("SKU", 10) + pad("MONTHS", 8) + pad("FOLDS", 7) + pad("WINNER", 16) +
    MODEL_IDS.map((id) => pad(id.toUpperCase(), 16)).join(""));
  for (const r of rows) {
    const flag = r.lowConfidence ? " (low confidence)" : "";
    console.log(
      pad(r.sku_id, 10) + pad(r.months, 8) + pad(r.foldsUsed, 7) + pad(r.winner + flag, 16) +
      MODEL_IDS.map((id) => pad(r.scores[id] == null ? "-" : r.scores[id], 16)).join("")
    );
  }
  console.log(`\n${rows.length} SKU(s), metric WMAPE (lower is better), low confidence = fewer than 6 scored folds.`);

  if (REPORT) {
    const fs = require("fs");
    const path = require("path");
    const lines = [
      "# Forecast backtest report", "",
      "Generated by `node backend/scripts/bench-forecast.js --report`. WMAPE, lower is better. Auto-mode picks the winner per SKU by this exact score.", "",
      `| SKU | Product | Months | Folds | Winner | ${MODEL_IDS.map((id) => id).join(" | ")} |`,
      `|---|---|---|---|---|${MODEL_IDS.map(() => "---").join("|")}|`,
      ...rows.map((r) =>
        `| ${r.sku_id} | ${r.name} | ${r.months} | ${r.foldsUsed} | ${r.winner}${r.lowConfidence ? " (low confidence)" : ""} | ${MODEL_IDS.map((id) => r.scores[id] ?? "-").join(" | ")} |`
      ),
    ];
    const out = path.join(__dirname, "..", "..", "docs", "forecast-backtest-report.md");
    fs.writeFileSync(out, lines.join("\n") + "\n");
    console.log(`\nWrote ${out}`);
  }
}

if (require.main === module) main();
module.exports = { main };
